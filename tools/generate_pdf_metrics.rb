# frozen_string_literal: true

# Generates ext/imprimatur_native/core/src/pdf/metrics.rs from Adobe's Core 14
# AFM files and pdf.js's WinAnsiEncoding glyph names:
#
#   curl -fsSLO https://download.macromedia.com/pub/developer/opentype/tech-notes/Core14_AFMs.zip
#   unzip Core14_AFMs.zip -d afm
#   curl -fsSLO https://raw.githubusercontent.com/mozilla/pdf.js/master/src/core/encodings.js
#   ruby tools/generate_pdf_metrics.rb afm encodings.js > ext/imprimatur_native/core/src/pdf/metrics.rs
#
# Only advance widths and vertical metrics are taken; kerning is not.

afm_dir, encodings_js = ARGV
abort 'usage: generate_pdf_metrics.rb AFM_DIR ENCODINGS_JS' unless afm_dir && encodings_js

# The faces the PDF writer uses; add Times or Courier here to offer them.
FONTS = %w[Helvetica Helvetica-Bold Helvetica-Oblique Helvetica-BoldOblique].freeze

source = File.read(encodings_js)
array = source[/const WinAnsiEncoding = \[(.*?)\];/m, 1] or abort 'WinAnsiEncoding not found'
win_ansi = array.scan(/"([^"]*)"/).flatten
abort "WinAnsiEncoding has #{win_ansi.size} entries, expected 256" unless win_ansi.size == 256

# Adobe's notices, verbatim: every copyright line of the fonts used, and the
# permission paragraph of MustRead.html.
copyrights = FONTS.flat_map do |font|
  File.foreach(File.join(afm_dir, "#{font}.afm"), encoding: 'ISO-8859-1').grep(/^Comment Copyright/)
end
copyrights = copyrights.map { it.delete_prefix('Comment ').strip }.uniq
readme = File.read(File.join(afm_dir, 'MustRead.html'), encoding: 'ISO-8859-1').gsub(/<[^>]+>/, ' ')
permission = readme[/This file and the 14 PostScript.*?use of the AFM files\./m]
abort 'permission paragraph not found' unless permission
permission = permission.gsub(/\s+/, ' ')

def doc_lines(text, width = 76)
  text.split.each_with_object([+'']) do |word, lines|
    lines << +'' if lines.last.length + word.length + 1 > width
    lines.last << (lines.last.empty? ? word : " #{word}")
  end.map { "//! #{it}" }
end

def metrics(path)
  widths = {}
  header = {}
  File.foreach(path, encoding: 'ISO-8859-1') do |line|
    if (glyph = line.match(/^C -?\d+ ; WX (\d+) ; N (\S+) ;/))
      widths[glyph[2]] = Integer(glyph[1])
    elsif (pair = line.match(/^(Ascender|Descender) (-?\d+)/))
      header[pair[1]] = Integer(pair[2])
    end
  end
  [widths, header]
end

# The Unicode character for each Windows-1252 byte 0x80..0x9F, as Ruby's
# own encoding table defines it; undefined bytes stay None.
high = (0x80..0x9F).map do |byte|
  byte.chr(Encoding::Windows_1252).encode(Encoding::UTF_8)
rescue EncodingError
  nil
end

puts <<~SOURCE
  //! Advance widths and vertical metrics of the PDF standard fonts, in
  //! thousandths of the font size, indexed by `WinAnsiEncoding` code.
  //!
  //! Generated by `tools/generate_pdf_metrics.rb`; do not edit. Derived
  //! (modified: reduced to widths and vertical metrics) from Adobe's Core 14
  //! AFM files, which carry these notices:
  //!
SOURCE
copyrights.each { |line| puts doc_lines(line) }
puts '//!'
puts doc_lines(permission)
puts
puts <<~SOURCE
  /// Metrics of one standard font.
  pub struct FontMetrics {
      pub name: &'static str,
      pub ascender: i16,
      pub descender: i16,
      /// 0 where `WinAnsiEncoding` has no glyph.
      pub widths: [u16; 256],
  }

  /// The Unicode character Windows-1252 assigns to bytes 0x80..=0x9F.
  pub const WIN_ANSI_HIGH: [Option<char>; 32] = [
SOURCE
high.each_slice(4) do |chars|
  puts "    #{chars.map { it ? "Some('\\u{#{it.ord.to_s(16)}}')" : 'None' }.join(', ')},"
end
puts "];\n\n"

FONTS.each do |font|
  widths, header = metrics(File.join(afm_dir, "#{font}.afm"))
  table = win_ansi.map { |name| name.empty? ? 0 : widths.fetch(name) { abort "#{font}: no glyph #{name}" } }
  constant = font.upcase.tr('-', '_')
  puts "pub const #{constant}: FontMetrics = FontMetrics {"
  puts "    name: #{font.inspect},"
  puts "    ascender: #{header.fetch('Ascender')},"
  puts "    descender: #{header.fetch('Descender')},"
  puts '    #[rustfmt::skip]'
  puts '    widths: ['
  table.each_slice(16) { |row| puts "        #{row.join(', ')}," }
  puts '    ],'
  puts "};\n\n"
end
