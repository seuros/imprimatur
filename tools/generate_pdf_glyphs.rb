# frozen_string_literal: true

# Generates ext/imprimatur_native/core/src/read/pdf/glyphs.txt, the data the
# PDF reader turns glyph names and character codes into text with: the Adobe
# Glyph List and ITC Zapf Dingbats list, then the five simple-font encodings
# of ISO 32000-1 Annex D (glyph names from pdf.js's encodings.js, resolved
# through the lists), then the presentation forms' compatibility
# decompositions. Lines are `name;HEX[ HEX...]`, the lists' own format;
# `@NAME` starts an encoding, whose lines are `code;HEX...` (decimal), and
# `@PRESENTATION` a section of `HEX;HEX...`.
#
#   curl -fsSLO https://raw.githubusercontent.com/adobe-type-tools/agl-aglfn/master/glyphlist.txt
#   curl -fsSLO https://raw.githubusercontent.com/adobe-type-tools/agl-aglfn/master/zapfdingbats.txt
#   curl -fsSLO https://raw.githubusercontent.com/mozilla/pdf.js/master/src/core/encodings.js
#   ruby tools/generate_pdf_glyphs.rb glyphlist.txt zapfdingbats.txt encodings.js \
#     > ext/imprimatur_native/core/src/read/pdf/glyphs.txt

glyphlist, zapfdingbats, encodings_js = ARGV
abort 'usage: generate_pdf_glyphs.rb GLYPHLIST ZAPFDINGBATS ENCODINGS_JS' unless encodings_js

def read_list(path)
  File.foreach(path).grep_v(/\A#/).to_h do |line|
    name, codes = line.chomp.split(';')
    [name, codes.split.map { it.to_i(16) }.pack('U*')]
  end
end

agl = read_list(glyphlist)
zapf = read_list(zapfdingbats)
notice = File.foreach(glyphlist).take_while { it.start_with?('#') }
                 .map { it.sub(/\A#\s?/, '').rstrip }
                 .drop_while(&:empty?).take_while { !it.start_with?('Format:') && !it.start_with?('Name:') }
notice.pop while notice.last&.match?(/\A-*\z/)

source = File.read(encodings_js)
encoding = lambda do |name, names|
  array = source[/const #{name} = \[(.*?)\];/m, 1] or abort "#{name} not found"
  glyphs = array.scan(/"([^"]*)"/).flatten
  abort "#{name} has #{glyphs.size} entries" unless glyphs.size == 256
  glyphs.map { names[it] || '' }
end
tables = {
  'STANDARD' => encoding.('StandardEncoding', agl),
  'WIN_ANSI' => encoding.('WinAnsiEncoding', agl),
  'MAC_ROMAN' => encoding.('MacRomanEncoding', agl),
  'SYMBOL' => encoding.('SymbolSetEncoding', agl),
  'ZAPF_DINGBATS' => encoding.('ZapfDingbatsEncoding', zapf)
}

puts '# Generated by tools/generate_pdf_glyphs.rb; do not edit.'
puts '#'
notice.each { puts "# #{it}".rstrip }
puts '@GLYPHS'
hex = ->(text) { text.each_char.map { format('%04X', it.ord) }.join(' ') }
agl.merge(zapf).sort_by { |name, _| name.b }.each { |name, text| puts "#{name};#{hex.(text)}" }
tables.each do |name, codes|
  puts "@#{name}"
  codes.each_with_index { |text, code| puts "#{code};#{hex.(text)}" unless text.empty? }
end
# Presentation forms (Hebrew, Arabic, and the Latin ligatures) as their
# compatibility decomposition, so extracted text searches like typed text.
puts '@PRESENTATION'
[(0xFB00..0xFDFF), (0xFE70..0xFEFF)].each do |range|
  range.each do |code|
    char = code.chr(Encoding::UTF_8)
    normalized = char.unicode_normalize(:nfkc)
    puts "#{format('%04X', code)};#{hex.(normalized)}" unless normalized == char
  rescue ArgumentError
    next
  end
end
